'use client'

import { Button } from '@/components/ui/button'
import { Badge } from '@/components/ui/badge'
import { Progress } from '@/components/ui/progress'
import {
  AlertDialog,
  AlertDialogAction,
  AlertDialogCancel,
  AlertDialogContent,
  AlertDialogDescription,
  AlertDialogFooter,
  AlertDialogHeader,
  AlertDialogTitle,
} from '@/components/ui/alert-dialog'
import { useToast } from '@/hooks/use-toast'
import { EditEntityDialog } from '@/components/edit-dialog'
import {
  BookOpen,
  GraduationCap,
  Loader2,
  Plus,
  Settings2,
  Trash2,
  CircleAlert,
  Pencil,
} from 'lucide-react'
import { useState } from 'react'
import type { CourseSummary } from '@/lib/types'

export function CourseLibrary({
  courses,
  loading,
  configured,
  demoMode,
  onOpenSettings,
  onNewCourse,
  onOpenCourse,
  onDeleteCourse,
  onEditCourse,
}: {
  courses: CourseSummary[]
  loading: boolean
  configured: boolean
  demoMode: boolean
  onOpenSettings: () => void
  onNewCourse: () => void
  onOpenCourse: (id: string) => void
  onDeleteCourse: (id: string) => void | Promise<void>
  onEditCourse: (id: string, values: { title: string; description: string }) => Promise<void>
}) {
  const [deletingId, setDeletingId] = useState<string | null>(null)
  const [editing, setEditing] = useState<CourseSummary | null>(null)
  // in-app confirm dialog instead of window.confirm(): native dialogs can be
  // permanently blocked by the browser ("prevent additional dialogs"), which
  // silently kills every later deletion
  const [confirmDelete, setConfirmDelete] = useState<CourseSummary | null>(null)
  const { toast } = useToast()

  const handleDeleteConfirmed = async () => {
    if (!confirmDelete) return
    const course = confirmDelete
    setConfirmDelete(null)
    setDeletingId(course.id)
    try {
      await onDeleteCourse(course.id)
    } catch (err) {
      toast({
        title: 'Delete failed',
        description: (err as Error)?.message || 'Could not delete this course. Please try again.',
        variant: 'destructive',
      })
    } finally {
      setDeletingId(null) // allow the next deletion
    }
  }

  return (
    <div className="min-h-screen flex flex-col">
      <header className="border-b border-zinc-800 bg-zinc-950/70 backdrop-blur sticky top-0 z-40">
        <div className="mx-auto max-w-5xl px-4 sm:px-6 h-16 flex items-center justify-between gap-3">
          <div className="flex items-center gap-2.5">
            <div className="h-9 w-9 rounded-lg bg-emerald-600 flex items-center justify-center">
              <GraduationCap className="h-5 w-5 text-white" />
            </div>
            <div>
              <h1 className="font-bold text-zinc-50 leading-tight">CourseForge</h1>
              <p className="text-xs text-zinc-500 leading-tight">
                Self-hosted AI course generator
              </p>
            </div>
          </div>
          <Button
            variant="outline"
            size="sm"
            onClick={onOpenSettings}
            className="border-zinc-700 text-zinc-300 hover:bg-zinc-800"
          >
            <Settings2 className="h-4 w-4 mr-1.5" />
            <span className="hidden sm:inline">API Settings</span>
            {!configured && <CircleAlert className="h-4 w-4 ml-1.5 text-amber-400" />}
          </Button>
        </div>
      </header>

      <main className="flex-1 mx-auto w-full max-w-5xl px-4 sm:px-6 py-10">
        {demoMode && (
          <div className="mb-8 flex items-start gap-3 rounded-xl border border-amber-800/60 bg-amber-950/30 p-4">
            <CircleAlert className="h-5 w-5 shrink-0 mt-0.5 text-amber-400" />
            <p className="text-sm leading-6 text-amber-200/90">
              <span className="font-semibold text-amber-300">Demo mode is active.</span> Courses are
              generated by the built-in demo model. Connect your own OpenAI-compatible API in{' '}
              <button
                onClick={onOpenSettings}
                className="underline underline-offset-2 hover:text-amber-100"
              >
                API Settings
              </button>{' '}
              to generate courses with your own model.
            </p>
          </div>
        )}
        <div className="text-center mb-10">
          <h2 className="text-3xl sm:text-4xl font-bold text-zinc-50 tracking-tight">
            Turn any topic into a full course
          </h2>
          <p className="mt-3 text-zinc-400 max-w-2xl mx-auto leading-7">
            Your own LLM endpoint writes structured curricula: modules, lessons with code examples,
            and quizzes — streamed live and stored locally in SQLite. No subscription, no data leaves
            your machine.
          </p>
          <div className="mt-6 flex justify-center">
            <Button
              size="lg"
              onClick={onNewCourse}
              disabled={!configured}
              className="bg-emerald-600 hover:bg-emerald-500 text-white h-11 px-6"
            >
              <Plus className="h-5 w-5 mr-2" /> Create your first course
            </Button>
          </div>
          {!configured && (
            <p className="mt-4 text-sm text-amber-400">
              First step: connect your OpenAI-compatible API in{' '}
              <button onClick={onOpenSettings} className="underline underline-offset-2">
                API Settings
              </button>
              .
            </p>
          )}
        </div>

        {loading ? (
          <div className="flex justify-center py-20 text-zinc-500">
            <Loader2 className="h-6 w-6 animate-spin" />
          </div>
        ) : courses.length === 0 ? (
          <div className="text-center py-16 text-zinc-600">
            <BookOpen className="h-10 w-10 mx-auto mb-3 opacity-40" />
            <p className="text-sm">No courses yet — create one above.</p>
          </div>
        ) : (
          <div className="grid gap-4 sm:grid-cols-2">
            {courses.map((c) => (
              <div
                key={c.id}
                className="group relative rounded-xl border border-zinc-800 bg-zinc-900/50 p-5 hover:border-emerald-700/60 transition-colors cursor-pointer"
                onClick={() => onOpenCourse(c.id)}
                role="button"
                tabIndex={0}
                onKeyDown={(e) => e.key === 'Enter' && onOpenCourse(c.id)}
              >
                <div className="flex items-start justify-between gap-2 mb-2">
                  <h3 className="font-semibold text-zinc-100 leading-snug pr-8">{c.title}</h3>
                  <Button
                    variant="ghost"
                    size="icon"
                    className="absolute right-3 top-3 h-7 w-7 text-zinc-600 hover:text-emerald-400 hover:bg-emerald-950/50 opacity-0 group-hover:opacity-100 transition-opacity"
                    onClick={(e) => {
                      e.stopPropagation()
                      setEditing(c)
                    }}
                    aria-label={`Edit ${c.title}`}
                  >
                    <Pencil className="h-4 w-4" />
                  </Button>
                  <Button
                    variant="ghost"
                    size="icon"
                    className="absolute right-11 top-3 h-7 w-7 text-zinc-600 hover:text-red-400 hover:bg-red-950/50 opacity-0 group-hover:opacity-100 transition-opacity"
                    onClick={(e) => {
                      e.stopPropagation()
                      if (deletingId) return
                      setConfirmDelete(c)
                    }}
                    aria-label={`Delete ${c.title}`}
                  >
                    {deletingId === c.id ? (
                      <Loader2 className="h-4 w-4 animate-spin" />
                    ) : (
                      <Trash2 className="h-4 w-4" />
                    )}
                  </Button>
                </div>
                <p className="text-sm text-zinc-400 leading-6 line-clamp-2 mb-4">
                  {c.description || c.topic}
                </p>
                <div className="flex items-center gap-2 mb-3 flex-wrap">
                  <Badge
                    variant="outline"
                    className="border-zinc-700 text-zinc-400 capitalize"
                  >
                    {c.difficulty}
                  </Badge>
                  <Badge variant="outline" className="border-zinc-700 text-zinc-400">
                    {c.totalLessons} lessons
                  </Badge>
                  {c.readyLessons === c.totalLessons ? (
                    <Badge className="bg-emerald-600/15 text-emerald-400 border border-emerald-700/50 hover:bg-emerald-600/15">
                      ready
                    </Badge>
                  ) : (
                    <Badge className="bg-amber-500/10 text-amber-400 border border-amber-700/50 hover:bg-amber-500/10">
                      {c.readyLessons}/{c.totalLessons} generated
                    </Badge>
                  )}
                </div>
                <Progress
                  value={(c.completedLessons / Math.max(1, c.totalLessons)) * 100}
                  className="h-1.5 bg-zinc-800"
                />
                <p className="mt-2 text-xs text-zinc-600">{c.model}</p>
              </div>
            ))}
          </div>
        )}
      </main>

      <footer className="border-t border-zinc-800 mt-auto">
        <div className="mx-auto max-w-5xl px-4 sm:px-6 py-4 flex flex-wrap items-center justify-between gap-2 text-xs text-zinc-600">
          <span>CourseForge — runs fully locally, data in SQLite.</span>
          <span>Bring your own LLM key.</span>
        </div>
      </footer>

      <AlertDialog
        open={Boolean(confirmDelete)}
        onOpenChange={(open) => !open && setConfirmDelete(null)}
      >
        <AlertDialogContent className="bg-zinc-900 border-zinc-800">
          <AlertDialogHeader>
            <AlertDialogTitle className="text-zinc-100">
              Delete “{confirmDelete?.title}”?
            </AlertDialogTitle>
            <AlertDialogDescription className="text-zinc-400">
              This permanently removes the course together with all its modules, lessons, quiz
              questions and chat history. This action cannot be undone.
            </AlertDialogDescription>
          </AlertDialogHeader>
          <AlertDialogFooter>
            <AlertDialogCancel className="border-zinc-700 text-zinc-300 hover:bg-zinc-800">
              Cancel
            </AlertDialogCancel>
            <AlertDialogAction
              onClick={(e) => {
                e.preventDefault() // keep the dialog open until we decide to close it
                handleDeleteConfirmed()
              }}
              className="bg-red-600 hover:bg-red-500 text-white"
            >
              {deletingId ? (
                <Loader2 className="h-4 w-4 animate-spin" />
              ) : (
                'Delete course'
              )}
            </AlertDialogAction>
          </AlertDialogFooter>
        </AlertDialogContent>
      </AlertDialog>

      <EditEntityDialog
        open={Boolean(editing)}
        onOpenChange={(open) => !open && setEditing(null)}
        title="Edit course"
        description="Rename the course or rewrite its description shown on this card."
        fields={[
          { key: 'title', label: 'Course title', required: true },
          { key: 'description', label: 'Description', multiline: true },
        ]}
        initial={{ title: editing?.title ?? '', description: editing?.description ?? '' }}
        onSave={async (values) => {
          if (!editing) return
          await onEditCourse(editing.id, {
            title: values.title,
            description: values.description,
          })
        }}
      />
    </div>
  )
}
